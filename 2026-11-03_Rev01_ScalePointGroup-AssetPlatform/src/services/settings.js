// Per-organisation settings stored in system_settings (jsonb). Defaults live here.
import { query } from '../db.js';
import { DEFAULT_MATCHING, mergeMatchingSettings } from '../../shared/engine.js';

export const SETTING_DEFAULTS = {
  matching: DEFAULT_MATCHING,
  reports: {
    requireApproval: true,          // reports generated by users without reports.approve start as drafts
    defaultTitle: 'Asset Condition Inspection Register',
    defaultPreparedBy: 'Scale Point Group',
    footerText: 'Prepared by Scale Point Group',
    mergeDuplicates: true,
    minAcceptableCondition: 3
  },
  registers: {
    requireSecondApprover: false,   // true: the uploader cannot approve their own register
    storeOriginalFiles: true
  },
  inspections: {
    storeOriginalFiles: true
  }
};

const KEYS = Object.keys(SETTING_DEFAULTS);
const cache = new Map(); // orgId -> { at, values }
const TTL = 30 * 1000;

function merge(key, saved) {
  if (key === 'matching') return mergeMatchingSettings(saved);
  const base = { ...SETTING_DEFAULTS[key] };
  if (saved && typeof saved === 'object') {
    for (const k of Object.keys(base)) {
      if (saved[k] !== undefined && typeof saved[k] === typeof base[k]) base[k] = saved[k];
    }
  }
  return base;
}

export async function getSettings(orgId) {
  const hit = cache.get(orgId);
  if (hit && Date.now() - hit.at < TTL) return hit.values;
  const r = await query('SELECT key, value FROM system_settings WHERE organisation_id = $1', [orgId]);
  const saved = Object.fromEntries(r.rows.map((x) => [x.key, x.value]));
  const values = Object.fromEntries(KEYS.map((k) => [k, merge(k, saved[k])]));
  cache.set(orgId, { at: Date.now(), values });
  return values;
}

export async function getSetting(orgId, key) {
  return (await getSettings(orgId))[key];
}

export function validateSetting(key, value) {
  if (!KEYS.includes(key)) throw new Error('Unknown setting group.');
  const merged = merge(key, value);
  if (key === 'matching') {
    const t = merged.thresholds;
    if (!(t.match > t.likely && t.likely > t.review && t.review > 0 && t.match <= 100)) throw new Error('Confidence bands must descend: Match > Likely > Review > 0.');
    const w = merged.weights;
    if (w.description + w.zone + w.location + w.keyword <= 0) throw new Error('At least one of description, zone, location or keyword needs a weight.');
    if (Object.values(w).some((v) => v < 0 || v > 100)) throw new Error('Weights must be between 0 and 100.');
    if (merged.synonyms.length > 50000) throw new Error('The synonym list is too long.');
  }
  if (key === 'reports') {
    const m = merged.minAcceptableCondition;
    if (!(Number.isInteger(m) && m >= 1 && m <= 4)) throw new Error('Minimum acceptable condition must be 1 to 4.');
    ['defaultTitle', 'defaultPreparedBy', 'footerText'].forEach((k) => { merged[k] = String(merged[k]).slice(0, 200); });
  }
  return merged;
}

export async function saveSetting(orgId, key, value, userId) {
  const merged = validateSetting(key, value);
  await query(
    `INSERT INTO system_settings (organisation_id, key, value, updated_by, updated_at) VALUES ($1, $2, $3, $4, now())
     ON CONFLICT (organisation_id, key) DO UPDATE SET value = EXCLUDED.value, updated_by = EXCLUDED.updated_by, updated_at = now()`,
    [orgId, key, JSON.stringify(merged), userId]
  );
  cache.delete(orgId);
  return merged;
}
